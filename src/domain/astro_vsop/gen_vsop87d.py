#!/usr/bin/env python3
"""Generate vsop87d_earth.inc from the CDS VSOP87D.ear file (catalogue VI/81).

Usage: gen_vsop87d.py VSOP87D.ear out.inc [cut]
Keeps terms with amplitude >= cut (default 2e-7: rad for L/B, AU for R)."""
import sys
src, out = sys.argv[1], sys.argv[2]
cut = float(sys.argv[3]) if len(sys.argv) > 3 else 2e-7
series = {}
cur = None
for line in open(src):
    if line.startswith(" VSOP87"):
        f = line.split()
        var = int(f[f.index("VARIABLE") + 1]); power = int(line.split("*T**")[1].split()[0])
        cur = (var, power); series[cur] = []
    else:
        t = line.split()
        a, b, c = float(t[-3]), float(t[-2]), float(t[-1])
        if abs(a) >= cut: series[cur].append((a, b, c))
names = {1: "L", 2: "B", 3: "R"}
with open(out, "w") as o:
    o.write("// Generated by gen_vsop87d.py from VSOP87D (Bretagnon & Francou 1988, CDS VI/81), Earth.\n")
    o.write("// Terms below %g (rad or AU) dropped. Do not edit by hand.\n\n" % cut)
    total = 0
    for var in (1, 2, 3):
        for p in range(6):
            s = series.get((var, p), [])
            total += len(s)
            o.write("const VsopTerm k%s%d[] = {\n" % (names[var], p))
            for i in range(0, len(s), 3):
                o.write(",".join("{%.11f,%.11f,%.11f}" % x for x in s[i:i+3]) + ",\n")
            if not s: o.write("{0,0,0}\n")
            o.write("};\n")
    print(total, "terms")
