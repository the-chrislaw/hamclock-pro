#!/usr/bin/env python3
"""Convert a pinned Natural Earth boundary-lines ZIP into bounded C++ arrays.

Only the exact root .shp member is read; no archive member is extracted.
No network access and no third-party Python packages.
"""
import argparse
import hashlib
import io
import math
from pathlib import Path
import struct
import zipfile

MAX_ARCHIVE = 1024 * 1024
MAX_SHP = 1024 * 1024
MAX_POINTS = 100000
MAX_PARTS = 10000
MEMBER = 'ne_110m_admin_0_boundary_lines_land.shp'
STATES_MEMBER = 'ne_110m_admin_1_states_provinces_lines.shp'


def decode_shp(data):
    if not 100 <= len(data) <= MAX_SHP:
        raise ValueError('shapefile size outside bounds')
    if struct.unpack_from('>I', data)[0] != 9994:
        raise ValueError('invalid shapefile magic')
    if struct.unpack_from('>I', data, 24)[0] * 2 != len(data):
        raise ValueError('invalid shapefile length')
    if struct.unpack_from('<II', data, 28) != (1000, 3):
        raise ValueError('expected version 1000 PolyLine shapefile')
    points, parts = [], []
    pos, record = 100, 1
    while pos < len(data):
        if pos + 8 > len(data):
            raise ValueError('truncated record header')
        number, words = struct.unpack_from('>II', data, pos)
        pos += 8
        size = words * 2
        if number != record or size < 44 or pos + size > len(data):
            raise ValueError('invalid record sequence or size')
        shape = struct.unpack_from('<I', data, pos)[0]
        if shape != 3:
            raise ValueError('only non-null PolyLine records supported')
        n_parts, n_points = struct.unpack_from('<II', data, pos + 36)
        if not 1 <= n_parts <= MAX_PARTS or not 2 <= n_points <= MAX_POINTS:
            raise ValueError('record counts outside bounds')
        if len(parts) + n_parts > MAX_PARTS or len(points) + n_points > MAX_POINTS:
            raise ValueError('aggregate counts outside bounds')
        if size != 44 + 4 * n_parts + 16 * n_points:
            raise ValueError('unexpected record payload length')
        starts = struct.unpack_from('<' + 'I' * n_parts, data, pos + 44)
        if starts[0] != 0 or any(a >= b for a, b in zip(starts, starts[1:])):
            raise ValueError('part offsets must start at zero and increase')
        ends = starts[1:] + (n_points,)
        if any(b > n_points or b - a < 2 for a, b in zip(starts, ends)):
            raise ValueError('invalid part bounds')
        base = len(points)
        parts.extend((base + a, b - a) for a, b in zip(starts, ends))
        offset = pos + 44 + 4 * n_parts
        for index in range(n_points):
            lon, lat = struct.unpack_from('<dd', data, offset + 16 * index)
            if not (math.isfinite(lat) and math.isfinite(lon)
                    and -90.000001 <= lat <= 90.000001 and -180.000001 <= lon <= 180.000001):
                raise ValueError('invalid geographic coordinate')
            # Source has four tiny +180 overshoots; snap only within 1e-6 degree.
            points.append((max(-180.0, min(180.0, lon)), max(-90.0, min(90.0, lat))))
        pos += size
        record += 1
    if not points:
        raise ValueError('empty borders')
    return points, parts


def read_zip(path, member_name=MEMBER):
    with path.open('rb') as stream:
        raw = stream.read(MAX_ARCHIVE + 1)
    if not 0 < len(raw) <= MAX_ARCHIVE:
        raise ValueError('archive size outside bounds')
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        matches = [item for item in archive.infolist() if item.filename == member_name]
        if len(matches) != 1:
            raise ValueError('expected exactly one root borders shapefile')
        member = matches[0]
        if member.flag_bits & 1 or not 100 <= member.file_size <= MAX_SHP:
            raise ValueError('encrypted or oversized shapefile')
        with archive.open(member) as stream:
            data = stream.read(MAX_SHP + 1)
        if len(data) != member.file_size:
            raise ValueError('uncompressed length mismatch')
    return decode_shp(data), hashlib.sha256(raw).hexdigest()


def emit(points, parts, sha, prefix='border'):
    P = prefix.capitalize()
    lines = ['#pragma once', '#include <cstddef>', '#include <cstdint>',
             '// Generated by tools/import_borders.py from Natural Earth public-domain data.',
             '// Geographic data are not covered by the application MIT copyright.',
             '// Source archive SHA-256: ' + sha, 'namespace hamclock {',
             'struct ' + P + 'Point { float longitude; float latitude; };',
             'struct ' + P + 'Part { std::uint32_t start; std::uint32_t count; };',
             'inline constexpr ' + P + 'Point ' + prefix + '_points[] = {']
    for lon, lat in points:
        lines.append('    {%.7ff, %.7ff},' % (lon, lat))
    lines += ['};', 'inline constexpr ' + P + 'Part ' + prefix + '_parts[] = {']
    lines += ['    {%du, %du},' % part for part in parts]
    lines += ['};', 'inline constexpr std::size_t ' + prefix + '_point_count = sizeof(' + prefix + '_points) / sizeof(' + prefix + '_points[0]);',
              'inline constexpr std::size_t ' + prefix + '_part_count = sizeof(' + prefix + '_parts) / sizeof(' + prefix + '_parts[0]);',
              '} // namespace hamclock', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--states', action='store_true', help='read admin-1 state/province lines (state_ names)')
    args = parser.parse_args()
    try:
        (points, parts), sha = read_zip(args.archive, STATES_MEMBER if args.states else MEMBER)
        args.output.write_text(emit(points, parts, sha, 'state' if args.states else 'border'), encoding='utf-8')
        print('SHA-256:', sha)
        print('Points:', len(points), 'Parts:', len(parts))
    except (ValueError, OSError, zipfile.BadZipFile, RuntimeError, struct.error) as error:
        parser.exit(2, 'Borderline import rejected: ' + str(error) + '\n')


if __name__ == '__main__':
    main()
