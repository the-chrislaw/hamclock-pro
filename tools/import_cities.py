#!/usr/bin/env python3
"""Convert the pinned Natural Earth 110m populated-places ZIP into a C++ array.

Only the exact root .shp and .dbf members are read; nothing is extracted.
Names use the ASCII column. No network access, standard library only.
"""
import argparse
import hashlib
import io
import math
from pathlib import Path
import struct
import zipfile

MAX_ARCHIVE = 1024 * 1024
MAX_MEMBER = 1024 * 1024
MAX_CITIES = 1000
BASE = 'ne_110m_populated_places_simple.'


def member(archive, ext):
    matches = [i for i in archive.infolist() if i.filename == BASE + ext]
    if len(matches) != 1 or matches[0].flag_bits & 1 or matches[0].file_size > MAX_MEMBER:
        raise ValueError('expected exactly one bounded .' + ext)
    with archive.open(matches[0]) as stream:
        data = stream.read(MAX_MEMBER + 1)
    if len(data) != matches[0].file_size:
        raise ValueError('uncompressed length mismatch')
    return data


def decode_dbf(data):
    count, header, record = struct.unpack_from('<IHH', data, 4)
    if not 0 < count <= MAX_CITIES or len(data) < header + count * record:
        raise ValueError('bad dbf counts')
    fields, offset = {}, 1
    for i in range(32, header - 1, 32):
        if data[i] == 0x0D:
            break
        fields[data[i:i + 11].split(b'\0')[0].decode()] = (offset, data[i + 16])
        offset += data[i + 16]
    rows = []
    for n in range(count):
        base = header + n * record
        row = {}
        for name in ('nameascii', 'pop_max'):
            start, length = fields[name]
            row[name] = data[base + start:base + start + length].decode('ascii').strip()
        rows.append(row)
    return rows


def decode_shp_points(data, count):
    if struct.unpack_from('>I', data)[0] != 9994 or struct.unpack_from('<II', data, 28) != (1000, 1):
        raise ValueError('expected a version 1000 Point shapefile')
    pos, points = 100, []
    for record in range(1, count + 1):
        number, words = struct.unpack_from('>II', data, pos)
        if number != record or words * 2 != 20 or struct.unpack_from('<I', data, pos + 8)[0] != 1:
            raise ValueError('invalid point record')
        lon, lat = struct.unpack_from('<dd', data, pos + 12)
        if not (math.isfinite(lat) and math.isfinite(lon) and -90 <= lat <= 90 and -180 <= lon <= 180):
            raise ValueError('invalid geographic coordinate')
        points.append((lon, lat))
        pos += 8 + words * 2
    if pos != len(data):
        raise ValueError('trailing shapefile data')
    return points


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    try:
        raw = args.archive.read_bytes()
        if not 0 < len(raw) <= MAX_ARCHIVE:
            raise ValueError('archive size outside bounds')
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            rows = decode_dbf(member(archive, 'dbf'))
            points = decode_shp_points(member(archive, 'shp'), len(rows))
        sha = hashlib.sha256(raw).hexdigest()
        lines = ['#pragma once', '#include <cstddef>',
                 '// Generated by tools/import_cities.py from Natural Earth public-domain data.',
                 '// Geographic data are not covered by the application MIT copyright.',
                 '// Source archive SHA-256: ' + sha, 'namespace hamclock {',
                 'struct City { const char* name; float latitude; float longitude; long population; };',
                 'inline constexpr City cities[] = {']
        for row, (lon, lat) in sorted(zip(rows, points), key=lambda t: -int(t[0]['pop_max'])):
            name = row['nameascii']
            if not name.isascii() or '"' in name or '\\' in name:
                raise ValueError('unexpected city name')
            lines.append('    {"%s", %.5ff, %.5ff, %dL},' % (name, lat, lon, int(row['pop_max'])))
        lines += ['};', 'inline constexpr std::size_t city_count = sizeof(cities) / sizeof(cities[0]);',
                  '} // namespace hamclock', '']
        args.output.write_text('\n'.join(lines), encoding='utf-8')
        print('SHA-256:', sha)
        print('Cities:', len(rows))
    except (ValueError, OSError, zipfile.BadZipFile, KeyError, struct.error) as error:
        parser.exit(2, 'City import rejected: ' + str(error) + '\n')


if __name__ == '__main__':
    main()
